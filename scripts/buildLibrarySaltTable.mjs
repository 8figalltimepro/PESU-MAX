// Builds src/helpers/librarySaltTable.js from a harvest of authenticated search
// results. Usage: node scripts/buildLibrarySaltTable.mjs <harvest.json>
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { courseCodeFromTitle, recordNumber } from "../src/helpers/libraryCourseCodes.js";

const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/helpers/librarySaltTable.js"
);

// "<salt><record label>.pdf", where the label is normally DL16049.
function splitFileName(recordId, downloadPath) {
  const fileName = String(downloadPath).split("/").pop().replace(/\.pdf$/i, "");
  const number = recordNumber(recordId);
  const markerIndex = number ? fileName.indexOf(number) : -1;
  const head = markerIndex >= 0 ? fileName.slice(0, markerIndex) : fileName;

  return { salt: head.replace(/dl$/i, ""), number };
}

function main() {
  const inputPath = process.argv[2];
  if (!inputPath) {
    console.error("usage: node scripts/buildLibrarySaltTable.mjs <harvest.json>");
    process.exit(1);
  }

  const harvest = JSON.parse(readFileSync(resolve(inputPath), "utf8"));
  const saltCounts = new Map();
  const saltNewest = new Map();
  const schemeSalts = new Map();
  const subjectSalts = new Map();
  const overrides = {};
  let skipped = 0;

  for (const [recordId, entry] of Object.entries(harvest)) {
    const downloadPath = entry?.downloadPath || entry?.path;
    if (!downloadPath) {
      skipped += 1;
      continue;
    }

    const { salt } = splitFileName(recordId, downloadPath);
    const number = recordNumber(recordId);

    // Files in a campus sub-directory, or named in a way the standard pattern
    // cannot build, are pinned by their exact path.
    const canonical = `digital/qp/${salt}DL${number}.pdf`.toLowerCase();
    if (number && String(downloadPath).toLowerCase() !== canonical) {
      overrides[number] = String(downloadPath).replace(/^\/+/, "");
    }

    if (!salt || salt.length > 12) {
      skipped += 1;
      continue;
    }

    saltCounts.set(salt, (saltCounts.get(salt) || 0) + 1);

    // Record ids are issued in upload order, so the highest id a salt appears
    // under doubles as its recency.
    const numericId = Number(number) || 0;
    saltNewest.set(salt, Math.max(saltNewest.get(salt) || 0, numericId));

    const courseCode = courseCodeFromTitle(entry.title);
    if (!courseCode) {
      continue;
    }

    if (!subjectSalts.has(courseCode)) {
      subjectSalts.set(courseCode, new Map());
    }
    const counts = subjectSalts.get(courseCode);
    counts.set(salt, Math.max(counts.get(salt) || 0, numericId));

    const scheme = courseCode.slice(0, 4);
    if (!schemeSalts.has(scheme)) {
      schemeSalts.set(scheme, new Map());
    }
    const schemes = schemeSalts.get(scheme);
    schemes.set(salt, Math.max(schemes.get(salt) || 0, numericId));
  }

  const byRecency = (entries) => [...entries]
    .sort((first, second) => second[1] - first[1] || first[0].localeCompare(second[0]))
    .map(([salt]) => salt);

  const subjects = {};
  for (const [courseCode, salts] of [...subjectSalts].sort()) {
    subjects[courseCode] = byRecency(salts);
  }

  const schemeTable = {};
  for (const [scheme, salts] of [...schemeSalts].sort()) {
    schemeTable[scheme] = byRecency(salts);
  }

  const table = {
    generatedAt: new Date().toISOString(),
    source: "authenticated OPAC search harvest (digital/qp filenames)",
    saltCount: saltCounts.size,
    salts: byRecency([...saltCounts.keys()].map((salt) => [salt, saltNewest.get(salt) || 0])),
    subjects,
    schemeSalts: schemeTable,
    overrides
  };

  writeFileSync(OUTPUT, [
    "// Generated by scripts/buildLibrarySaltTable.mjs - do not edit by hand.",
    `export const LIBRARY_SALT_TABLE = ${JSON.stringify(table, null, 2)};`,
    "",
    "export default LIBRARY_SALT_TABLE;",
    ""
  ].join("\n"));

  console.log(
    `wrote ${OUTPUT}\n  records=${Object.keys(harvest).length} skipped=${skipped}`
    + ` salts=${table.saltCount} subjects=${Object.keys(subjects).length}`
    + ` overrides=${Object.keys(overrides).length}`
    + ` schemes=${Object.keys(schemeTable).length}`
  );
}

main();
